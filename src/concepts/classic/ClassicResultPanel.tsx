import type { DetectionReport } from '../../types/detection';

export type ResultState =
  | { kind: 'idle' }
  | { kind: 'analyzing' }
  | { kind: 'demo-report'; report: DetectionReport }
  | { kind: 'unavailable' };

type Props = {
  state: ResultState;
};

/** Thin semicircular confidence gauge. Neutral when score is null. */
function ConfidenceGauge({ score }: { score: number | null }) {
  const r = 54;
  const cx = 70;
  const cy = 68;
  const stroke = 7;
  const circumference = Math.PI * r;
  const clamped = score == null ? 0 : Math.min(100, Math.max(0, score));
  const dash = (clamped / 100) * circumference;

  return (
    <div className="classic-gauge" role="img" aria-label={score == null ? 'Awaiting analysis' : `AI detection ${score.toFixed(2)}%`}>
      <svg className="classic-gauge-svg" viewBox="0 0 140 88" width="160" height="100" aria-hidden="true">
        <path
          className="classic-gauge-track"
          d={`M ${cx - r} ${cy} A ${r} ${r} 0 0 1 ${cx + r} ${cy}`}
          fill="none"
          strokeWidth={stroke}
          strokeLinecap="round"
        />
        {score != null && (
          <path
            className="classic-gauge-fill"
            d={`M ${cx - r} ${cy} A ${r} ${r} 0 0 1 ${cx + r} ${cy}`}
            fill="none"
            strokeWidth={stroke}
            strokeLinecap="round"
            strokeDasharray={`${dash} ${circumference}`}
            style={{ transition: 'stroke-dasharray 280ms ease' }}
          />
        )}
      </svg>
      <p className="classic-gauge-value">{score == null ? '—%' : `${score.toFixed(2)}%`}</p>
    </div>
  );
}

export default function ClassicResultPanel({ state }: Props) {
  const score =
    state.kind === 'demo-report' ? state.report.score : null;

  return (
    <section className="classic-result" aria-labelledby="classic-result-heading">
      <header className="classic-pane-header">
        <h2 id="classic-result-heading" className="classic-pane-label">
          {state.kind === 'demo-report' ? 'AI Detection Result' : 'AI Detection'}
        </h2>
      </header>

      <div
        className="classic-result-body"
        aria-live="polite"
        aria-busy={state.kind === 'analyzing'}
      >
        <ConfidenceGauge score={score} />

        {state.kind === 'idle' && (
          <div className="classic-result-copy">
            <p className="classic-result-status">Awaiting analysis.</p>
            <p className="classic-result-explain">
              After you run Detect AI, a confidence reading and passage notes appear here.
            </p>
            <ul className="classic-result-features">
              <li>Sentence highlights</li>
              <li>Detailed analysis</li>
              <li>PDF report</li>
            </ul>
            <p className="classic-result-hint">Feature descriptions — not a completed result.</p>
          </div>
        )}

        {state.kind === 'analyzing' && (
          <div className="classic-result-copy">
            <p className="classic-result-status">Analyzing…</p>
            <p className="classic-result-explain">Preparing demonstration insights.</p>
          </div>
        )}

        {state.kind === 'unavailable' && (
          <div className="classic-result-copy">
            <p className="classic-result-status">Live analysis is not connected in this concept preview.</p>
            <p className="classic-result-explain">
              Your text is preserved. Edit and try again — arbitrary submissions do not receive
              fabricated scores.
            </p>
            <p className="classic-result-hint">
              With <code>?demo=1</code>, the predefined sample document shows the fixture report.
            </p>
          </div>
        )}

        {state.kind === 'demo-report' && (
          <div className="classic-result-copy">
            <p className="classic-result-status">{state.report.classification}</p>
            <p className="classic-result-legend">
              <span className="classic-result-swatch" aria-hidden="true" />
              Highly likely passages
            </p>
            <p className="classic-result-explain">
              Highlighted passages in your text match the Integrito demonstration fixture. This is
              an illustrative reading, not definitive proof of authorship.
            </p>
            {state.report.isDemo && (
              <p className="classic-result-demo" role="note">
                Predefined demonstration result. Not generated by a live detector.
              </p>
            )}
          </div>
        )}
      </div>
    </section>
  );
}
